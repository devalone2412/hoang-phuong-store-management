import { z } from "zod";

const price = z
  .number({ error: "Nhập số tiền hợp lệ" })
  .int("Giá phải là số nguyên")
  .min(0, "Giá không được âm")
  .max(1_000_000_000, "Giá quá lớn");

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Tối đa ${max} ký tự`)
    .nullish()
    .transform((v) => (v ? v : null));

export const MAX_COMBOS = 5;

const comboSchema = z.object({
  quantity: z
    .number({ error: "Nhập số lượng" })
    .int("Số lượng phải là số nguyên")
    .min(2, "Combo từ 2 trở lên")
    .max(9999, "Số lượng quá lớn"),
  price,
});
export type Combo = z.infer<typeof comboSchema>;

/** Keys are generated by POST /api/images; this is also the only shape the image route serves. */
export const IMAGE_KEY_RE = /^[0-9a-f-]{36}\.(jpg|png|webp)$/;

export { THUMB_KEY_RE, thumbKey } from "@/lib/image-keys";

export const MAX_BARCODES = 10;

const barcodesSchema = z
  .array(z.string().trim().min(1, "Mã vạch không được để trống").max(40, "Tối đa 40 ký tự"))
  .max(MAX_BARCODES, `Tối đa ${MAX_BARCODES} mã vạch`)
  .refine((list) => new Set(list).size === list.length, "Có mã vạch bị trùng nhau")
  .default([]);

/** Shared by the form (react-hook-form) and the API route handlers. */
export const WEIGHT_UNIT = "kg";

const productFields = z.object({
  name: z.string().trim().min(1, "Nhập tên sản phẩm").max(200, "Tối đa 200 ký tự"),
  // Optional here: weighed products always use kg. Required for the rest by the refine below.
  unit: z.string().trim().max(30, "Tối đa 30 ký tự").default(""),
  /** Sold by weight: `retailPrice` is per kg, the unit is kg and combos don't apply. */
  soldByWeight: z.boolean().default(false),
  retailPrice: price,
  costPrice: price.nullish().transform((v) => v ?? null),
  category: optionalText(60),
  sku: optionalText(40),
  barcodes: barcodesSchema,
  note: optionalText(500),
  combos: z
    .array(comboSchema)
    .max(MAX_COMBOS, `Tối đa ${MAX_COMBOS} combo`)
    .refine((list) => new Set(list.map((c) => c.quantity)).size === list.length, "Mỗi số lượng chỉ có một giá combo")
    .default([])
    .transform((list) => [...list].sort((a, b) => a.quantity - b.quantity)),
  /** Weighed products only: price of 100 g, charged under 1 kg. Empty = `retailPrice` ÷ 10. */
  price100g: price.nullish().transform((v) => v ?? null),
  imageKey: z
    .string()
    .regex(IMAGE_KEY_RE, "Ảnh không hợp lệ")
    .nullish()
    .transform((v) => v ?? null),
});

export const productInputSchema = productFields
  .superRefine((p, ctx) => {
    if (!p.soldByWeight && !p.unit) ctx.addIssue({ code: "custom", path: ["unit"], message: "Nhập đơn vị tính" });
    if (p.soldByWeight && p.combos.length > 0) {
      ctx.addIssue({ code: "custom", path: ["combos"], message: "Hàng bán theo cân không dùng combo" });
    }
    if (!p.soldByWeight && p.price100g !== null) {
      ctx.addIssue({ code: "custom", path: ["price100g"], message: "Chỉ dùng cho hàng bán theo cân" });
    }
  })
  .transform((p) => (p.soldByWeight ? { ...p, unit: WEIGHT_UNIT } : p));

export type ProductInput = z.input<typeof productInputSchema>;
export type ProductData = z.output<typeof productInputSchema>;

/** Price-order sanity check. A warning for the UI, never a validation error. */
export function priceWarnings(p: {
  retailPrice?: number | null;
  costPrice?: number | null;
  /** Weighed products: price of 100 g. */
  price100g?: number | null;
}): string[] {
  const out: string[] = [];
  const { retailPrice: r, costPrice: c, price100g: h } = p;
  if (r != null && c != null && c > r) out.push("Giá vốn đang cao hơn giá lẻ.");
  if (r != null && h != null && h * 10 < r) out.push("Giá / 100 g đang rẻ hơn giá / kg.");
  return out;
}

/** A combo that costs as much or more per unit than buying singly is probably a typo. */
export function comboWarnings(retailPrice: number | null | undefined, combos: { quantity?: number; price?: number }[]) {
  if (retailPrice == null || Number.isNaN(retailPrice)) return [];
  return combos
    .filter((c) => c.quantity && c.price != null && !Number.isNaN(c.price) && c.price >= c.quantity * retailPrice)
    .map((c) => `Combo ${c.quantity} không rẻ hơn mua lẻ.`);
}

/** What the API returns for one product. */
export type Product = {
  id: string;
  name: string;
  sku: string | null;
  /** The first one is the primary barcode. */
  barcodes: string[];
  unit: string;
  category: string | null;
  /** True: `retailPrice` is per kg and quantities are weights in grams. */
  soldByWeight: boolean;
  retailPrice: number;
  costPrice: number | null;
  combos: Combo[];
  /** Weighed products: price of 100 g, charged under 1 kg. Null = `retailPrice` ÷ 10. */
  price100g: number | null;
  imageKey: string | null;
  note: string | null;
  createdAt: number;
  updatedAt: number;
};

export const listQuerySchema = z.object({
  q: z.string().trim().max(100).default(""),
  category: z.string().trim().max(60).optional(),
  sort: z.enum(["name", "retailPrice", "updatedAt"]).default("updatedAt"),
  dir: z.enum(["asc", "desc"]).default("desc"),
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(5).max(100).default(20),
});
export type ListQuery = z.infer<typeof listQuerySchema>;
